// The parts of the measurements that decide something: which process belongs to the demo, what a chord
// sends, where a median falls, whose bytes a stretch of the bundle is. Pure, so calculations.test.mjs
// pins them; demo-instance.mjs and measure.mjs feed them /proc, DevTools and the build.

// Whether one process is the demo's, given its process group and the NUL-separated contents of its
// /proc cmdline and environ. Whole entries are compared, never substrings: an unrelated shell whose
// PWD or OLDPWD sits under the demo folder must not match HOME=<demo>/home.
export function isDemoProcess({ processGroup, commandLine, environment }, { group, home, userData }) {
  if (processGroup === group) return true;
  return commandLine.split('\0').includes(`--user-data-dir=${userData}`) || environment.split('\0').includes(`HOME=${home}`);
}

const KEY_CODES = { Enter: 13, Escape: 27, Tab: 9, ArrowDown: 40, ArrowUp: 38, ArrowLeft: 37, ArrowRight: 39, Backspace: 8 };

// One chord, `Ctrl+Shift+T`, `Alt+2`, `ArrowDown`, `x`, as the DevTools Input.dispatchKeyEvent fields a
// keyboard would produce. `text` is set only for a key that types something: a modified chord with
// text would type its character into the focused pane as well as run the shortcut.
export function keyEvent(chord) {
  const parts = chord.split('+');
  const key = parts.pop();
  const modifiers = (parts.includes('Alt') ? 1 : 0) | (parts.includes('Ctrl') ? 2 : 0) | (parts.includes('Meta') ? 4 : 0) | (parts.includes('Shift') ? 8 : 0);
  const single = key.length === 1;
  const shown = single && parts.includes('Shift') ? key.toUpperCase() : single ? key.toLowerCase() : key;
  const code = single ? (/\d/.test(key) ? `Digit${key}` : `Key${key.toUpperCase()}`) : key;
  const keyCode = single ? key.toUpperCase().charCodeAt(0) : KEY_CODES[key] ?? 0;
  const text = single && !(modifiers & 7) ? shown : key === 'Enter' && !modifiers ? '\r' : undefined;
  return { base: { modifiers, key: shown, code, windowsVirtualKeyCode: keyCode, nativeVirtualKeyCode: keyCode }, text };
}

// Median, p90 and max by nearest rank, the figures every latency line in history.md gives.
export function spread(values) {
  const sorted = [...values].sort((a, b) => a - b);
  const at = (quantile) => sorted[Math.min(sorted.length - 1, Math.floor(quantile * sorted.length))];
  return { samples: sorted.length, median: at(0.5), p90: at(0.9), max: sorted.at(-1) };
}

// A source path as the package (or src/ folder) it belongs to.
export function ownerOf(source) {
  const packagePath = source.includes('node_modules/') ? source.split('node_modules/').pop() : null;
  if (packagePath) return packagePath.split('/').slice(0, packagePath.startsWith('@') ? 2 : 1).join('/');
  return 'src/' + (source.split('src/')[1] ?? source).split('/').slice(0, 2).join('/');
}

const DIGITS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

// One base64 VLQ segment of a source map as its signed values.
export function decodeSegment(segment) {
  const values = [];
  let shift = 0, value = 0;
  for (const character of segment) {
    const digit = DIGITS.indexOf(character);
    value += (digit & 31) << shift;
    if (digit & 32) shift += 5;
    else { values.push(value & 1 ? -(value >> 1) : value >> 1); value = 0; shift = 0; }
  }
  return values;
}

// Generated bytes per source index from a v3 `mappings` string and the generated lines' lengths. Per
// segment the column and the source index are running totals. A segment with only a column maps to no
// source, and its bytes go to -1 rather than to whichever source came before it.
export function bytesPerSource(mappings, lineLengths) {
  const bytes = new Map();
  let source = 0;
  mappings.split(';').forEach((line, row) => {
    let column = 0;
    const segments = [];
    for (const segment of line.split(',')) {
      if (!segment) continue;
      const values = decodeSegment(segment);
      column += values[0];
      if (values.length > 1) source += values[1];
      segments.push([column, values.length > 1 ? source : -1]);
    }
    segments.forEach(([start, index], position) => {
      const end = position + 1 < segments.length ? segments[position + 1][0] : lineLengths[row];
      bytes.set(index, (bytes.get(index) ?? 0) + end - start);
    });
  });
  return bytes;
}
